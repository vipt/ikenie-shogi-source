const { chromium } = require('playwright');
const fs = require('node:fs/promises');
const assert = require('node:assert/strict');
let browser;

(async () => {
  await fs.mkdir('artifacts/screenshots', { recursive: true });
  browser = await chromium.launch({ channel: 'chrome', headless: true });
  const page = await browser.newPage({ viewport: { width: 1280, height: 1040 }, deviceScaleFactor: 1 });
  const errors = [];
  page.on('pageerror', error => errors.push(String(error)));
  await page.goto('http://localhost:8082');
  await page.getByTestId('shogi-board').waitFor();
  await page.screenshot({ path: 'artifacts/screenshots/desktop.png', fullPage: true });
  await page.getByRole('button', { name: '新しい対局 ↗' }).click();
  await page.getByRole('radio', { name: /ふたりで対局/ }).click();
  await page.getByTestId('start-game').click();
  await page.getByTestId('square-70').click();
  assert.match(await page.getByTestId('square-61').getAttribute('aria-label'), /回収できる/);
  await page.screenshot({ path: 'artifacts/screenshots/recovery.png', fullPage: true });
  await page.getByTestId('square-61').click();
  assert.match(await page.getByTestId('hand-sente-P').getAttribute('aria-label'), /1枚/);
  await page.getByTestId('square-10').click();
  await page.getByTestId('square-19').click();
  assert.match(await page.getByTestId('hand-gote-P').getAttribute('aria-label'), /1枚/);
  await page.getByTestId('hand-sente-P').click();
  assert.match(await page.getByTestId('square-43').getAttribute('aria-label'), /移動できる/);
  await page.getByTestId('square-43').click();
  assert.match(await page.getByTestId('square-43').getAttribute('aria-label'), /先手の歩/);
  await page.reload();
  await page.getByTestId('shogi-board').waitFor();
  assert.match(await page.getByTestId('square-43').getAttribute('aria-label'), /先手の歩/);
  await page.getByRole('button', { name: '↶ 待った', exact: true }).click();
  assert.match(await page.getByTestId('square-43').getAttribute('aria-label'), /空きマス/);
  assert.match(await page.getByTestId('hand-sente-P').getAttribute('aria-label'), /1枚/);
  await page.getByTestId('square-76').click();
  assert.doesNotMatch(await page.getByTestId('square-75').getAttribute('aria-label'), /回収できる/);
  await page.getByRole('button', { name: '遊び方を開く' }).click();
  await page.getByText('生贄将棋の遊び方').waitFor();
  await page.getByRole('button', { name: '盤に戻る' }).click();
  await page.getByRole('button', { name: '新しい対局 ↗' }).click();
  await page.getByRole('radio', { name: /ひとりで練習/ }).click();
  await page.getByRole('radio', { name: '強め', exact: true }).click();
  await page.getByTestId('start-game').click();
  await page.getByTestId('square-70').click();
  await page.getByTestId('square-61').click();
  await page.getByText('先手の番です', { exact: true }).waitFor();
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('meguru-shogi.v1')));
  assert.equal(saved.moves.length, 2);
  assert.equal(saved.settings.difficulty, 'strong');
  await page.getByRole('button', { name: '↶ 待った', exact: true }).click();
  assert.match(await page.getByTestId('square-70').getAttribute('aria-label'), /先手の飛/);
  // Cancel a live search and ensure it cannot append a stale move.
  await page.getByTestId('square-70').click();
  await page.getByTestId('square-61').click();
  await page.getByText('こまめが考えています', { exact: true }).waitFor();
  await page.getByRole('button', { name: '↶ 待った', exact: true }).click();
  await page.waitForTimeout(2800);
  assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('meguru-shogi.v1')).moves.length), 0);
  await page.getByRole('button', { name: '投了', exact: true }).click();
  await page.getByRole('button', { name: '投了する', exact: true }).click();
  await page.getByTestId('game-result').waitFor();
  assert.equal(await page.getByRole('dialog').count(), 0, 'game over stays on the board');
  await page.getByText('後手の勝ち', { exact: true }).first().waitFor();

  const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
  mobile.on('pageerror', error => errors.push(String(error)));
  await mobile.goto('http://localhost:8082');
  await mobile.getByTestId('shogi-board').waitFor();
  await mobile.screenshot({ path: 'artifacts/screenshots/mobile.png', fullPage: true });
  const overflow = await mobile.evaluate(() => document.documentElement.scrollWidth > window.innerWidth);
  assert.equal(overflow, false, 'mobile page must not overflow horizontally');
  const cells = await mobile.getByTestId('shogi-board').locator('[data-testid^="square-"]').count();
  assert.equal(cells, 81);
  await mobile.getByTestId('square-70').tap();
  await mobile.screenshot({ path: 'artifacts/screenshots/mobile-selected.png', fullPage: true });
  await mobile.getByTestId('square-61').tap();
  await mobile.getByText('先手の番です', { exact: true }).waitFor();
  await mobile.setViewportSize({ width: 320, height: 568 });
  assert.equal(await mobile.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false);
  await mobile.screenshot({ path: 'artifacts/screenshots/small-mobile.png', fullPage: true });
  assert.deepEqual(errors, []);
  console.log('UI PASS: recovery, drops, king restriction, CPU response, undo, persistence, rules, resign, 390px and 320px layouts; no runtime errors.');
  await browser.close();
})().catch(async error => { console.error(error); await browser?.close(); process.exitCode = 1; });
